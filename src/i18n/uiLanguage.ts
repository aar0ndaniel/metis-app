function withOriginalSpacing(original: string, translated: string): string {
  const leading = original.match(/^\s*/)?.[0] ?? ''
  const trailing = original.match(/\s*$/)?.[0] ?? ''
  return `${leading}${translated}${trailing}`
}

function escapeRegExp(value: string): string {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function replaceSegment(text: string, source: string, replacement: string): string {
  const pattern = new RegExp(`(^|[^A-Za-zÀ-ÖØ-öø-ÿ])(${escapeRegExp(source)})(?=$|[^A-Za-zÀ-ÖØ-öø-ÿ])`, 'gi')
  return text.replace(pattern, (_match, prefix) => `${prefix}${replacement}`)
}

function translateWithGlossary(text: string, language: Exclude<UiLanguage, 'English'>): string {
  let translated = text
  const entries = GLOSSARY_TRANSLATIONS[language].slice().sort((a, b) => b[0].length - a[0].length)
  for (const [source, replacement] of entries) {
    translated = replaceSegment(translated, source, replacement)
  }
  return translated
}

type RelativeAgeUnit = 'minute' | 'hour' | 'day' | 'week'

const RELATIVE_AGE_TRANSLATIONS: Record<TranslatedLanguage, Record<RelativeAgeUnit, [string, string]>> = {
  Español: {
    minute: ['minuto', 'minutos'],
    hour: ['hora', 'horas'],
    day: ['día', 'días'],
    week: ['semana', 'semanas'],
  },
  Português: {
    minute: ['minuto', 'minutos'],
    hour: ['hora', 'horas'],
    day: ['dia', 'dias'],
    week: ['semana', 'semanas'],
  },
  Français: {
    minute: ['minute', 'minutes'],
    hour: ['heure', 'heures'],
    day: ['jour', 'jours'],
    week: ['semaine', 'semaines'],
  },
}

function translateRelativeAge(source: string, language: TranslatedLanguage): string | null {
  if (/^just now$/i.test(source)) {
    if (language === 'Español') return 'ahora mismo'
    if (language === 'Português') return 'agora mesmo'
    return 'à l’instant'
  }

  const match = source.match(/^(\d+)\s+(minute|minutes|hour|hours|day|days|week|weeks)\s+ago$/i)
  if (!match) return null

  const count = Number(match[1])
  const rawUnit = match[2].toLowerCase()
  const unit = (rawUnit.endsWith('s') ? rawUnit.slice(0, -1) : rawUnit) as RelativeAgeUnit
  const [singular, plural] = RELATIVE_AGE_TRANSLATIONS[language][unit]
  const noun = count === 1 ? singular : plural

  if (language === 'Español') return `hace ${count} ${noun}`
  if (language === 'Português') return `há ${count} ${noun}`
  return `il y a ${count} ${noun}`
}

function canUseGlossaryFallback(text: string): boolean {
  if (KNOWN_GLOSSARY_UI_PHRASES.has(text)) return true
  const words = text.toLowerCase().match(/[a-zà-öø-ÿ]+/giu) ?? []
  if (!words.length) return false
  return words.every((word) => (
    GLOSSARY_SOURCE_WORDS.has(word) ||
    GLOSSARY_STOPWORDS.has(word) ||
    DOMAIN_WORDS.has(word)
  ))
}

export function normalizeUiLanguage(value: unknown): UiLanguage {
  const language = String(value ?? '').trim().toLowerCase()
  if (language === 'español' || language === 'spanish' || language.startsWith('es')) return 'Español'
  if (language === 'português' || language === 'portuguese' || language.startsWith('pt')) return 'Português'
  if (language === 'français' || language === 'french' || language.startsWith('fr')) return 'Français'
  return 'English'
}

export function getSavedUiLanguage(): UiLanguage {
  try {
    return normalizeUiLanguage(localStorage.getItem(METIS_PREF_LANGUAGE_KEY) ?? localStorage.getItem(LEGACY_PREF_LANGUAGE_KEY))
  } catch {
    return 'English'
  }
}

export function getSystemUiLanguage(): UiLanguage {
  if (typeof navigator === 'undefined') return 'English'
  const candidates = [
    ...(Array.isArray(navigator.languages) ? navigator.languages : []),
    navigator.language,
  ]
  for (const candidate of candidates) {
    const language = normalizeUiLanguage(candidate)
    if (language !== 'English' || String(candidate ?? '').toLowerCase().startsWith('en')) return language
  }
  return 'English'
}

export function translateUiText(text: string, language: UiLanguage): string {
  if (language === 'English') return text
  const source = text.trim().replace(/\s+/g, ' ')
  if (!source) return text
  const exact = EXACT_TRANSLATIONS[source]?.[language]
  if (exact) return withOriginalSpacing(text, exact)
  const relativeAge = translateRelativeAge(source, language)
  if (relativeAge) return withOriginalSpacing(text, relativeAge)
  if (!canUseGlossaryFallback(source)) return text
  const translated = translateWithGlossary(source, language)
  return translated === source ? text : withOriginalSpacing(text, translated)
}
