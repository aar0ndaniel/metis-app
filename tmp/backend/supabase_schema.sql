-- Website events remain useful for diagnostics, but are not added to the
-- GitHub count because the same user may also download directly from GitHub.
create table if not exists public.release_download_events (
  id bigint generated by default as identity primary key,
  version text not null,
  build_variant text not null check (build_variant in ('bundle', 'lite')),
  platform text not null check (platform in ('windows', 'mac-arm', 'mac-intel')),
  asset_name text not null,
  asset_url text not null,
  source text not null default 'website' check (source in ('website', 'github')),
  created_at timestamptz not null default timezone('utc', now())
);

create index if not exists idx_release_download_events_asset
  on public.release_download_events (version, platform, build_variant, created_at desc);

create or replace view public.view_download_counts as
select
  version,
  platform,
  build_variant,
  asset_name,
  github_asset_url,
  github_download_count as total_downloads,
  github_download_count,
  website_click_count,
  github_synced_at
from public.release_download_assets
order by version desc, platform, build_variant;

create or replace function public.sync_github_release_asset_download_count(
  p_version text,
  p_asset_name text,
  p_download_count bigint,
  p_synced_at timestamptz default timezone('utc', now())
) returns void
language sql
security definer
set search_path = public
as $$
  update public.release_download_assets
  set github_download_count = greatest(p_download_count, 0),
      github_synced_at = p_synced_at,
      updated_at = timezone('utc', now())
  where version = p_version and asset_name = p_asset_name;
$$;
